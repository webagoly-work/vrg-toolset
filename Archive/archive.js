#!/usr/bin/env node
// ---------------------------------------------------------------------------
// archive.js — the VRG Artifact Archive (Artifaktum-archívum): one container for every one-shot interactive HTML page
// Claude made (published claude.ai artifacts and local one-off pages), each with a short note on what it is, when it was
// made, what was going on in the work at the time and why it was wanted.
//
//   Archive/index.json     the source: { version, about, groups, items[] }  (edit this, or use `add`)
//   Archive/index.js       generated from index.json (window.VRG_ARCHIVE = …) so the page also works from file://
//   Archive/files/<id>.html  the saved copy of each page (localPath instead: a page kept where it is, e.g. it needs files beside it)
//   Archive/vrg-archive.html the viewer (START, VRG Asztal in-shell app, Dashboard section "Archívum")
//
//   node Archive/archive.js list                      every entry, VRG first
//   node Archive/archive.js check                     exit 1 on a bad entry, a missing copy or a stale index.js
//   node Archive/archive.js build                     rewrite index.js from index.json
//   node Archive/archive.js add <page.html> --title "…" [--id x] [--url https://claude.ai/artifact/…] [--group "VRG core"]
//        [--vrg] [--kind tool] [--lang hu] [--created YYYY-MM-DD] [--summary "…"] [--purpose "…"] [--context "a|b"] [--tags "x,y"]
//
// Pure functions are exported for the VRG Asztal (Dashboard/shell/main.js: the archive.* IPC) and the tests.
// ---------------------------------------------------------------------------
'use strict';
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
const KINDS = ['tool', 'explainer', 'mockup', 'board', 'game', 'manual', 'study', 'dashboard', 'design'];
const ID_RE = /^[a-z0-9][a-z0-9-]{0,47}$/;
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const URL_RE = /^https:\/\/claude\.ai\/(code\/)?artifact\/[A-Za-z0-9-]+$/;

const paths = (dir = DIR) => ({ dir, index: path.join(dir, 'index.json'), js: path.join(dir, 'index.js'), files: path.join(dir, 'files') });

function read(dir = DIR) {
  const j = JSON.parse(fs.readFileSync(paths(dir).index, 'utf8'));
  if (!j || !Array.isArray(j.items)) throw new Error('archive: index.json has no items array');
  return j;
}

// VRG first, then the rest; newest first inside each half
function sorted(items) {
  return [...items].sort((a, b) => (b.vrg === true) - (a.vrg === true) || String(b.created).localeCompare(String(a.created)) || a.title.localeCompare(b.title));
}

// every problem with the index, as strings (empty = fine)
function validate(j, dir = DIR) {
  const errs = [];
  const seen = new Set();
  for (const [n, it] of (j.items || []).entries()) {
    const at = 'item ' + n + (it && it.id ? ' (' + it.id + ')' : '');
    if (!it || typeof it !== 'object') { errs.push(at + ': not an object'); continue; }
    if (!ID_RE.test(it.id || '')) errs.push(at + ': bad id');
    if (seen.has(it.id)) errs.push(at + ': duplicate id'); seen.add(it.id);
    if (typeof it.title !== 'string' || !it.title.trim()) errs.push(at + ': no title');
    if (!DATE_RE.test(it.created || '')) errs.push(at + ': created is not YYYY-MM-DD');
    if (it.updated !== undefined && !DATE_RE.test(it.updated)) errs.push(at + ': updated is not YYYY-MM-DD');
    if (typeof it.vrg !== 'boolean') errs.push(at + ': vrg must be true or false');
    if (it.kind !== undefined && !KINDS.includes(it.kind)) errs.push(at + ': kind must be one of ' + KINDS.join(', '));
    if (it.url !== undefined && !URL_RE.test(it.url)) errs.push(at + ': url is not a claude.ai artifact link');
    if (!it.url && !it.file && !it.localPath) errs.push(at + ': neither url, file nor localPath');
    if (it.file !== undefined) {
      if (!/^files\/[a-z0-9][a-z0-9-]{0,47}\.html$/.test(it.file)) errs.push(at + ': file must be files/<id>.html');
      else if (!fs.existsSync(path.join(dir, it.file))) errs.push(at + ': ' + it.file + ' is missing');
    }
    for (const k of ['context', 'tags']) if (it[k] !== undefined && (!Array.isArray(it[k]) || it[k].some(s => typeof s !== 'string'))) errs.push(at + ': ' + k + ' must be a list of strings');
  }
  return errs;
}

const jsText = j => '// generated by Archive/archive.js build from index.json; do not edit\nwindow.VRG_ARCHIVE = ' + JSON.stringify(j, null, 1) + ';\n';
function build(dir = DIR) {
  const j = read(dir);
  j.items = sorted(j.items);
  fs.writeFileSync(paths(dir).js, jsText(j));
  return j;
}
const stale = (dir = DIR) => { try { const j = read(dir); j.items = sorted(j.items); return fs.readFileSync(paths(dir).js, 'utf8') !== jsText(j); } catch (e) { return true; } };

const slug = s => String(s || '').normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40) || 'artifact';
const today = () => new Date().toISOString().slice(0, 10);
const titleOf = html => { const m = /<title[^>]*>([^<]{1,200})<\/title>/i.exec(html); return m ? m[1].trim() : ''; };

// add one page: copy the HTML into files/<id>.html and append its entry (an existing id is refused, never overwritten)
function add(src, meta = {}, dir = DIR) {
  const html = fs.readFileSync(src, 'utf8');
  if (!/<html|<body|<script|<svg|<div/i.test(html)) throw new Error('archive: ' + src + ' does not look like an HTML page');
  const j = read(dir);
  const title = String(meta.title || titleOf(html) || path.basename(src, path.extname(src))).trim();
  let id = meta.id || slug(title);
  if (!meta.id) { let n = 2; const base = id; while (j.items.some(i => i.id === id)) id = base + '-' + n++; }
  if (j.items.some(i => i.id === id)) throw new Error('archive: id ' + id + ' already exists');
  const it = {
    id, title, created: meta.created || today(), updated: meta.updated || meta.created || today(), lang: meta.lang || 'hu', vrg: meta.vrg === true,
    group: meta.group || (meta.vrg ? 'VRG core' : 'Other'), kind: meta.kind || 'explainer',
    summary: meta.summary || '', purpose: meta.purpose || '', context: meta.context || [], tags: meta.tags || [],
    file: 'files/' + id + '.html',
  };
  if (meta.url) it.url = meta.url;
  const errs = validate({ items: [...j.items, { ...it, file: undefined, url: it.url || 'https://claude.ai/artifact/x' }] }, dir);
  if (errs.length) throw new Error('archive: ' + errs.join('; '));
  fs.mkdirSync(paths(dir).files, { recursive: true });
  fs.writeFileSync(path.join(dir, it.file), html);
  j.items.push(it);
  j.items = sorted(j.items);
  fs.writeFileSync(paths(dir).index, JSON.stringify(j, null, 2) + '\n');
  build(dir);
  return it;
}

// what the VRG Asztal's Dashboard section shows: the light fields only, VRG first
function list(dir = DIR) {
  const j = read(dir);
  return { groups: j.groups || {}, items: sorted(j.items).map(i => ({ id: i.id, title: i.title, created: i.created, vrg: i.vrg, group: i.group, kind: i.kind, summary: i.summary, saved: !!i.file, url: i.url || '' })) };
}

function argv(a) {
  const o = { _: [] };
  for (let i = 0; i < a.length; i++) {
    if (a[i] === '--vrg') o.vrg = true;
    else if (a[i].startsWith('--')) o[a[i].slice(2)] = a[++i];
    else o._.push(a[i]);
  }
  return o;
}

function main() {
  const o = argv(process.argv.slice(2));
  const cmd = o._[0] || 'list';
  if (cmd === 'list') {
    for (const i of sorted(read().items)) console.log((i.vrg ? 'VRG ' : '    ') + i.created + '  ' + (i.file ? 'saved ' : 'link  ') + i.id.padEnd(30) + i.title);
    return 0;
  }
  if (cmd === 'build') { const j = build(); console.log('index.js written, ' + j.items.length + ' entries'); return 0; }
  if (cmd === 'check') {
    const errs = validate(read());
    if (stale()) errs.push('index.js is stale: run node Archive/archive.js build');
    for (const e of errs) console.log('FAIL ' + e);
    const j = read();
    console.log(errs.length ? errs.length + ' problem(s)' : 'ok: ' + j.items.length + ' entries, ' + j.items.filter(i => i.file).length + ' saved copies');
    return errs.length ? 1 : 0;
  }
  if (cmd === 'add') {
    if (!o._[1]) { console.log('usage: node Archive/archive.js add <page.html> --title "…" [options]'); return 1; }
    const split = (s, re) => (s ? s.split(re).map(x => x.trim()).filter(Boolean) : undefined);
    const it = add(path.resolve(o._[1]), { ...o, context: split(o.context, /\|/), tags: split(o.tags, /,/) });
    console.log('added ' + it.id + ' -> Archive/' + it.file);
    return 0;
  }
  console.log('unknown command: ' + cmd);
  return 1;
}

module.exports = { KINDS, read, sorted, validate, build, stale, add, list, slug, titleOf, paths };
if (require.main === module) process.exitCode = main();
