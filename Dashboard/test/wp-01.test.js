// WP-01: the Dashboard moved into the repo. Reads the real registries (read only); writes only inside Dashboard/.
'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs'), path = require('path');
const build = require('../build.js');

const DASH = path.resolve(__dirname, '..');

test('collect() hands out the START acts, including s:C/1', () => {
  const c = build.collect();
  const ids = Object.keys(c.startActs);
  assert.ok(ids.length >= 20, 'startActs has ' + ids.length);
  assert.ok(ids.includes('s:C/1'));
  assert.strictEqual(c.claude, 's:C/1');
});

test('paths.REPO is the folder above Dashboard/', () => {
  const c = build.collect();
  assert.strictEqual(path.resolve(c.paths.REPO), path.resolve(DASH, '..'));
  assert.strictEqual(path.resolve(path.dirname(build.OUT)), DASH);
});

test('write() writes dashboard-data.js next to build.js', () => {
  const before = fs.existsSync(build.OUT) ? fs.statSync(build.OUT).mtimeMs : 0;
  build.write();
  assert.ok(fs.existsSync(build.OUT));
  assert.ok(fs.statSync(build.OUT).mtimeMs >= before);
  assert.match(fs.readFileSync(build.OUT, 'utf8'), /^\/\/ generated by Dashboard\/build\.js[^\n]*\nwindow\.VRG_DASH = \{/);
});

test('the page links the shared stylesheet from the repo', () => {
  const html = fs.readFileSync(path.join(DASH, 'vrg-dashboard.html'), 'utf8');
  assert.ok(html.includes('<link rel="stylesheet" href="../shared/melyviz.css">'));
  assert.ok(fs.existsSync(path.join(DASH, '..', 'shared', 'melyviz.css')));
});
