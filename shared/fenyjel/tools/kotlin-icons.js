#!/usr/bin/env node
/* Fényjel — tools/kotlin-icons.js (rollout R1): the pixel icons for VRG Mobile, from the one source.
   Reads shared/fenyjel/icons.js (the glyph grids and their families) and fenyjel.css (the family colours) and writes
     Mobile/android/kit-core/src/main/kotlin/hu/vrg/mobile/core/PixelGlyphs.kt
   pure Kotlin data (no Android), so kit-core's FeatureIconsTest can check it against the sources without the SDK;
   kit/ui/PixelIcon.kt draws it.
     node shared/fenyjel/tools/kotlin-icons.js           write the file
     node shared/fenyjel/tools/kotlin-icons.js --check   exit 1 when the file differs from what the sources give
     node shared/fenyjel/tools/kotlin-icons.js --print   write it to stdout */
'use strict';
const fs = require('fs');
const path = require('path');

const FJ = path.join(__dirname, '..');
const REPO = path.join(FJ, '..', '..');
const OUT = path.join(REPO, 'Mobile', 'android', 'kit-core', 'src', 'main', 'kotlin', 'hu', 'vrg', 'mobile', 'core', 'PixelGlyphs.kt');

/** Family id → 0xRRGGBB from fenyjel.css: --fj-f-<id>, and "ui" = --fj-ink. */
function familyColours() {
  const css = fs.readFileSync(path.join(FJ, 'fenyjel.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  const root = (css.match(/:root\s*\{([\s\S]*?)\n\}/) || [])[1] || '';
  const out = {};
  root.replace(/--fj-f-(\w+):\s*#([0-9a-fA-F]{6})\s*;/g, (m, k, v) => { out[k] = v.toUpperCase(); return m; });
  const ink = /--fj-ink:\s*#([0-9a-fA-F]{6})\s*;/.exec(root);
  if (!ink) throw new Error('fenyjel.css has no --fj-ink');
  out.ui = ink[1].toUpperCase();
  return out;
}

const kq = s => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$') + '"';

function generate() {
  delete require.cache[require.resolve(path.join(FJ, 'icons.js'))];
  const I = require(path.join(FJ, 'icons.js'));
  const cols = familyColours();
  Object.keys(I.FAMILIES).forEach(f => { if (!cols[f]) throw new Error('no colour for family ' + f + ' in fenyjel.css'); });
  const L = [];
  L.push('// GENERATED by shared/fenyjel/tools/kotlin-icons.js from shared/fenyjel/icons.js (the glyphs) and fenyjel.css (the');
  L.push('// family colours). Do not edit by hand: change icons.js, then run `node shared/fenyjel/tools/kotlin-icons.js`.');
  L.push('// `--check` (CI, mobile.cmd test) fails on drift; kit-core FeatureIconsTest checks this file against the sources.');
  L.push('package hu.vrg.mobile.core');
  L.push('');
  L.push('/** One Fényjel pixel glyph (shared/fenyjel/DESIGN.md §5): 12 rows of 12, `#` lit, `+` dim, `.` off. */');
  L.push('data class PixelGlyph(val name: String, val family: String, val hu: String, val rows: List<String>)');
  L.push('');
  L.push('/** The Fényjel pixel icon set as data. kit/ui/PixelIcon.kt draws it; FeatureIcons maps the catalogue onto it. */');
  L.push('object PixelGlyphs {');
  L.push('    const val SIZE = ' + I.N);
  L.push('');
  L.push('    /** Function family → its colour (0xRRGGBB): what a thing does decides its colour. "ui" is the ink. */');
  L.push('    val FAMILY_COLOURS: Map<String, Int> = mapOf(');
  Object.keys(I.FAMILIES).forEach(f => L.push('        ' + kq(f) + ' to 0x' + cols[f] + ',   // ' + I.FAMILIES[f].hu));
  L.push('    )');
  L.push('');
  L.push('    /** Function family → its Hungarian name (icons.js FAMILIES). */');
  L.push('    val FAMILY_NAMES: Map<String, String> = mapOf(');
  Object.keys(I.FAMILIES).forEach(f => L.push('        ' + kq(f) + ' to ' + kq(I.FAMILIES[f].hu) + ','));
  L.push('    )');
  L.push('');
  L.push('    val ALL: Map<String, PixelGlyph> = listOf(');
  I.list().forEach(ic => {
    const g = I.ICONS[ic.name];
    L.push('        PixelGlyph(' + kq(ic.name) + ', ' + kq(g.family) + ', ' + kq(g.hu) + ', listOf(');
    for (let r = 0; r < g.rows.length; r += 4) L.push('            ' + g.rows.slice(r, r + 4).map(kq).join(', ') + ',');
    L.push('        )),');
  });
  L.push('    ).associateBy { it.name }');
  L.push('');
  L.push('    /** The 5×7 LED numerals (DESIGN.md §5.1): every number on a Fényjel screen. Narrow signs (":", ".") are narrower. */');
  L.push('    val DIGITS: Map<Char, List<String>> = mapOf(');
  Object.keys(I.DIGITS).forEach(ch => L.push("        '" + (ch === "'" || ch === '\\' ? '\\' + ch : ch) + "' to listOf(" + I.DIGITS[ch].map(kq).join(', ') + '),'));
  L.push('    )');
  L.push('');
  L.push('    fun byName(name: String?): PixelGlyph? = if (name == null) null else ALL[name]');
  L.push('}');
  L.push('');
  return L.join('\n');
}

function main() {
  const args = process.argv.slice(2);
  const text = generate();
  if (args.includes('--print')) { process.stdout.write(text); return; }
  if (args.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (now !== text) { console.log('x PixelGlyphs.kt differs from shared/fenyjel/icons.js. Run: node shared/fenyjel/tools/kotlin-icons.js'); process.exit(1); }
    console.log('ok PixelGlyphs.kt matches shared/fenyjel/icons.js');
    return;
  }
  fs.writeFileSync(OUT, text);
  console.log('ok wrote ' + path.relative(REPO, OUT));
}

module.exports = { generate, familyColours };
if (require.main === module) main();
