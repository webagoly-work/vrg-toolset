#!/usr/bin/env node
// publish-city.js — VRG Mobile, WP M5 (Kódváros online, D-7 = A): put one branch's city on `city-pages`.
//
//   node Mobile/city/publish-city.js --branch <name> --from <dir with city.html + city.json> [--push]
//   node Mobile/city/publish-city.js --branch <name> --remove [--push]
//        [--repo .] [--remote origin] [--sha <commit the city was scanned from>] [--run-url <Actions run>]
//
// Without --push it is a dry run: it builds the new city-pages commit in the repo's object store and prints
// what would change, but sends nothing. .github/workflows/mobile-city.yml runs it with --push.
//
// The layout of city-pages (the phone's feature-city and kit-core City.kt read exactly this):
//   README.md
//   city/<key>/city.html   the whole Kódváros page with the city inside (CodeCity/scan.js --html)
//   city/<key>/city.json   the data alone (scan.js --out)
//   city/<key>/meta.json   {kind:'vrg-city-meta', branch, key, sha, head, scannedAt, commits, files, htmlBytes, run}
// <key> is the branch name made safe for one path segment and a URL: [A-Za-z0-9_-] and a '.' that is not
// first stay, every other byte of the UTF-8 name becomes ~xx (lower-case hex). So `claude/m5` -> `claude~2fm5`,
// one folder per branch, never nested, and the name comes back exactly (branchOf). Mobile/tests/fixtures/city-keys.json
// holds the cases both sides are tested against.
//
// How it writes, and what it never touches:
// - Only git plumbing on a private index file (GIT_INDEX_FILE): read-tree of the current city-pages tip,
//   replace city/<key>/, write-tree, commit-tree. The working tree, the real index, HEAD and every local
//   branch stay as they were; the source branch is never written.
// - Each publish is ONE root commit (no parent) holding every branch's city: the branch never grows a
//   history of multi-megabyte pages, so a `git fetch` of the repo stays cheap. That needs a forced push, and
//   it is the only one in the toolset: --force-with-lease on refs/heads/city-pages alone, against the tip it
//   read. A publish that raced another one is rejected by the lease, reads the new tip and tries again (5x),
//   so the other branch's city is never lost.
'use strict';
const fs = require('fs'), path = require('path'), os = require('os'), { execFileSync } = require('child_process');

const PAGES = 'city-pages';
const FILES = ['city.html', 'city.json', 'meta.json'];
const RAW_LIMIT = 95 * 1024 * 1024;   // GitHub's raw contents API serves files up to 100 MB
const TIP = 'refs/city-publish/tip';  // a private ref for the fetched tip: no branch is created or moved

const README = `# city-pages: Kódváros online (VRG Mobile, WP M5)

Generated by \`.github/workflows/mobile-city.yml\` on every push: \`CodeCity/scan.js\` runs on the pushed branch
in Actions and \`Mobile/city/publish-city.js\` puts its city here. Do not commit to this branch by hand; it is
replaced (one commit, no history) on every publish.

- \`city/<key>/city.html\`: the Kódváros page with that branch's city inside; VRG Mobile shows it (Kódváros online).
- \`city/<key>/city.json\`: the data alone; \`city/<key>/meta.json\`: branch, commit, scan time, sizes.
- \`<key>\` is the branch name with every byte outside [A-Za-z0-9._-] written as ~xx (\`claude/x\` -> \`claude~2fx\`).

The city shows what is in the repository on GitHub, never a PC's working copy.
`;

// ---- the key: a branch name as one safe path segment ----------------------------------------------
function key(branch) {
  if (typeof branch !== 'string' || !branch) throw new Error('empty branch name');
  let out = '';
  for (const b of Buffer.from(branch, 'utf8')) {
    const c = String.fromCharCode(b);
    if (/[A-Za-z0-9_-]/.test(c) || (c === '.' && out.length > 0)) out += c;
    else out += '~' + b.toString(16).padStart(2, '0');
  }
  return out;
}

/** The branch a key stands for, or null when the key is not one key() could have written. */
function branchOf(k) {
  if (typeof k !== 'string' || !k) return null;
  const bytes = [];
  for (let i = 0; i < k.length; i++) {
    const c = k[i];
    if (c === '~') {
      const h = k.slice(i + 1, i + 3);
      if (!/^[0-9a-f]{2}$/.test(h)) return null;
      const b = parseInt(h, 16);
      const raw = String.fromCharCode(b);
      if (/[A-Za-z0-9_-]/.test(raw) || (raw === '.' && i > 0)) return null;   // key() would have kept it as is
      bytes.push(b); i += 2;
    } else if (/[A-Za-z0-9_-]/.test(c) || (c === '.' && i > 0)) bytes.push(c.charCodeAt(0));
    else return null;
  }
  const buf = Buffer.from(bytes);
  const s = buf.toString('utf8');
  return Buffer.from(s, 'utf8').equals(buf) ? s : null;   // invalid UTF-8 does not round-trip
}

const dirOf = branch => `city/${key(branch)}`;

// ---- meta.json ---------------------------------------------------------------------------------------
function meta({ branch, sha, runUrl, city, htmlBytes }) {
  const r = (city && city.repo) || {};
  return {
    kind: 'vrg-city-meta', version: 1,
    branch, key: key(branch), sha: sha || '', head: r.head || (sha || '').slice(0, 7),
    scannedAt: r.scannedAt || new Date().toISOString(),
    commits: Array.isArray(city && city.commits) ? city.commits.length : 0,
    files: Array.isArray(city && city.files) ? city.files.filter(f => !f.gone).length : 0,
    htmlBytes, run: runUrl || '',
  };
}

// ---- publish --------------------------------------------------------------------------------------------
function publish(o) {
  const repo = path.resolve(o.repo || '.');
  const remote = o.remote || 'origin';
  const log = o.log || (s => console.log(s));
  const branch = o.branch;
  if (!branch) throw new Error('--branch is required');
  if (branch === PAGES) throw new Error(`${PAGES} itself has no city`);
  const k = key(branch), dir = `city/${k}`;
  const git = (args, extra = {}, input) => execFileSync('git', args, {
    cwd: repo, encoding: 'utf8', input, maxBuffer: 1 << 28,
    stdio: [input === undefined ? 'ignore' : 'pipe', 'pipe', 'pipe'],
    env: { ...process.env, ...extra },
  }).trim();

  // what goes in: city.html + city.json from --from, meta.json written here
  let blobs = [];
  if (!o.remove) {
    const from = path.resolve(o.from || '');
    const html = path.join(from, 'city.html'), data = path.join(from, 'city.json');
    for (const f of [html, data]) if (!fs.existsSync(f)) throw new Error(`missing ${f} (run CodeCity/scan.js --out/--html first)`);
    const htmlBytes = fs.statSync(html).size;
    if (htmlBytes > RAW_LIMIT || fs.statSync(data).size > RAW_LIMIT) throw new Error('the city is over 95 MB: GitHub\'s raw contents API would not serve it');
    const city = JSON.parse(fs.readFileSync(data, 'utf8'));
    if (city.kind !== 'vrg-codecity') throw new Error(`${data} is not a Kódváros city`);
    const sha = o.sha || git(['rev-parse', 'HEAD']);
    const m = JSON.stringify(meta({ branch, sha, runUrl: o.runUrl, city, htmlBytes }), null, 1) + '\n';
    blobs = [
      ['city.html', git(['hash-object', '-w', '--', html])],
      ['city.json', git(['hash-object', '-w', '--', data])],
      ['meta.json', git(['hash-object', '-w', '--stdin'], {}, m)],
    ];
  }
  const readme = git(['hash-object', '-w', '--stdin'], {}, README);
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'vrg-city-'));
  const env = { GIT_INDEX_FILE: path.join(tmp, 'index') };
  const who = { GIT_AUTHOR_NAME: 'VRG city', GIT_AUTHOR_EMAIL: 'vrg-city@users.noreply.github.com',
    GIT_COMMITTER_NAME: 'VRG city', GIT_COMMITTER_EMAIL: 'vrg-city@users.noreply.github.com' };

  try {
    for (let attempt = 1; attempt <= 5; attempt++) {
      // the current tip, into a private ref (no branch is created or moved)
      const listed = git(['ls-remote', '--heads', remote, `refs/heads/${PAGES}`]);
      let parent = null;
      if (listed) {
        // --refmap= : no opportunistic refs/remotes/<remote>/city-pages either
        git(['fetch', '--quiet', '--no-tags', '--refmap=', remote, `+refs/heads/${PAGES}:${TIP}`]);
        parent = git(['rev-parse', TIP]);
      }
      git(parent ? ['read-tree', parent] : ['read-tree', '--empty'], env);
      git(['rm', '--cached', '-r', '-q', '--ignore-unmatch', '--', dir], env);
      for (const [name, sha] of blobs) git(['update-index', '--add', '--cacheinfo', `100644,${sha},${dir}/${name}`], env);
      git(['update-index', '--add', '--cacheinfo', `100644,${readme},README.md`], env);
      const tree = git(['write-tree'], env);
      const before = parent ? git(['rev-parse', `${parent}^{tree}`]) : null;
      const branches = git(['ls-tree', '--name-only', tree, 'city/'], env).split('\n').filter(Boolean).map(p => p.slice(5));
      if (tree === before) {
        log(`${PAGES}: unchanged (${o.remove ? 'no city' : 'the same city'} for ${branch})`);
        return { changed: false, pushed: false, key: k, dir, branches };
      }
      const msg = o.remove ? `city: ${branch} removed (the branch is gone)` : `city: ${branch} @ ${(o.sha || git(['rev-parse', 'HEAD'])).slice(0, 7)}`;
      const commit = git(['commit-tree', tree, '-m', msg], { ...env, ...who });
      if (o.beforePush) o.beforePush(attempt);   // tests: another publisher gets in first
      if (!o.push) {
        log(`${PAGES}: dry run, would publish ${commit.slice(0, 7)} (${o.remove ? 'removing' : 'writing'} ${dir}/; ${branches.length} cities: ${branches.join(', ') || '-'})`);
        return { changed: true, pushed: false, commit, tree, key: k, dir, branches };
      }
      try {
        git(['push', '--quiet', `--force-with-lease=refs/heads/${PAGES}:${parent || ''}`, remote, `${commit}:refs/heads/${PAGES}`]);
        log(`${PAGES}: ${msg} -> ${commit.slice(0, 7)} (${branches.length} cities)`);
        return { changed: true, pushed: true, commit, tree, key: k, dir, branches, attempts: attempt };
      } catch (e) {
        log(`${PAGES}: push ${attempt} refused (${String(e.stderr || e.message).trim().split('\n').pop()}), reading the new tip`);
      }
    }
    throw new Error(`${PAGES}: gave up after 5 refused pushes`);
  } finally {
    try { git(['update-ref', '-d', TIP]); } catch { /* never fetched */ }
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

module.exports = { PAGES, FILES, key, branchOf, dirOf, meta, publish };

if (require.main === module) {
  const argv = process.argv.slice(2);
  const opt = k => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : undefined; };
  const flag = k => argv.includes(k);
  try {
    publish({
      branch: opt('--branch'), from: opt('--from'), repo: opt('--repo'), remote: opt('--remote'),
      sha: opt('--sha'), runUrl: opt('--run-url'), remove: flag('--remove'), push: flag('--push'),
    });
  } catch (e) {
    console.error(`publish-city: ${e.message}`);
    process.exit(1);
  }
}
