#!/usr/bin/env node
// Mobile/catalogue/ports-gen.js — writes ports.json (WP M8): port -> tool, for the relay's ports.list.
//
// The source is START's registry, launcher/vrg-menu.json `servers` (CLAUDE.md: a tool that is not
// there does not exist), so a server added to START gets its name on the phone after one run of:
//
//   node Mobile/catalogue/ports-gen.js            (writes ports.json)
//   node Mobile/catalogue/ports-gen.js --check    (exit 1 when ports.json is out of date; the test runs it)
//
// EXTRA lists the ports START does not start but the toolset uses.
const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..', '..');
const MENU = path.join(REPO, 'launcher', 'vrg-menu.json');
const OUT = path.join(__dirname, 'ports.json');

const EXTRA = [
  { port: 5037, id: 'adb', name: 'adb szerver', path: '/' },
];

function build() {
  const menu = JSON.parse(fs.readFileSync(MENU, 'utf8'));
  const seen = new Set();
  const ports = [];
  for (const s of menu.servers || []) {
    if (!Number.isInteger(s.port) || seen.has(s.port)) continue;
    seen.add(s.port);
    ports.push({ port: s.port, id: s.id, name: s.name, path: typeof s.open === 'string' && s.open.startsWith('/') ? s.open : '/' });
  }
  for (const e of EXTRA) if (!seen.has(e.port)) { seen.add(e.port); ports.push(e); }
  ports.sort((a, b) => a.port - b.port);
  return JSON.stringify({
    about: 'Generated by Mobile/catalogue/ports-gen.js from launcher/vrg-menu.json servers. Do not edit by hand.',
    ports,
  }, null, 2) + '\n';
}

if (require.main === module) {
  const text = build();
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (now !== text) { console.log('ports.json is out of date: node Mobile/catalogue/ports-gen.js'); process.exit(1); }
    console.log('ports.json is up to date');
  } else {
    fs.writeFileSync(OUT, text);
    console.log('wrote ' + path.relative(REPO, OUT));
  }
}

module.exports = { build, OUT };
