// VRG Mobile's launcher icon: the Varler mark (the original bulb, leaves and E27 base, without the wordmark), once per
// palette, so the icon on the phone's home screen wears the colours the user picked in Beállítások → Megjelenés.
//
// Inputs (never edit the outputs by hand):
//   shared/varler-logo/lockups/lockups.json      the mark's path (`mark`, the same in every lockup)
//   Mobile/android/kit/.../theme/Melyviz.kt      the app's palettes (id, abyss, glow)
//   Mobile/android/kit/.../theme/KitTokens.kt    the four VRG UI Kit palettes
// Outputs:
//   kit/src/main/res/drawable/vk_varler_mark.xml               the mark alone, white (the home's watermark tints it)
//   app/src/main/res/drawable/ic_launcher_mark_<id>.xml        the icon's foreground, in that palette's glow
//   app/src/main/res/drawable/ic_launcher_mono.xml             Android 13+ themed icons (the system tints it)
//   app/src/main/res/values/launcher_icons.xml                 the backgrounds (each palette's abyss)
//   app/src/main/res/mipmap-anydpi-v26/ic_launcher[_<id>].xml  the adaptive icons
//   app/src/main/AndroidManifest.xml, between the launcher-aliases markers: one activity-alias per palette, the
//     Mélyvíz one enabled; the app switches them with PackageManager (app/LauncherIcon.kt).
//
//   node Mobile/catalogue/icon-gen.js           write them
//   node Mobile/catalogue/icon-gen.js --check   exit 1 when any is out of date (mobile.cmd test and CI run it)
'use strict';
const fs = require('fs'), path = require('path');
const REPO = path.resolve(__dirname, '..', '..');
const A = p => path.join(REPO, 'Mobile', 'android', p);

const mark = require(path.join(REPO, 'shared/varler-logo/lockups/lockups.json'))[0].mark;

// ---- the palettes, in the app's order (Palettes.ALL = the seven + KitTokens.ALL) -------------------------------
function palettes(file) {
  const src = fs.readFileSync(file, 'utf8');
  const out = [];
  const re = /Palette\(\s*"([a-z0-9-]+)",\s*"([^"]*)",\s*(true|false)/g;
  const starts = [...src.matchAll(re)];
  starts.forEach((m, i) => {
    const block = src.slice(m.index, i + 1 < starts.length ? starts[i + 1].index : src.length);
    const col = k => { const c = block.match(new RegExp(`\\b${k} = Color\\(0x([0-9A-Fa-f]{8})\\)`)); if (!c) throw new Error(`${m[1]}: no ${k}`); return '#' + c[1].toUpperCase(); };
    const css = {};      // every colour of the palette, #RRGGBB, for the iPhone web app (M36)
    for (const c of block.matchAll(/\b(\w+) = Color\(0x([0-9A-Fa-f]{2})([0-9A-Fa-f]{6})\)/g)) css[c[1]] = '#' + c[3].toUpperCase();
    out.push({ id: m[1], name: m[2], light: m[3] === 'true', abyss: col('abyss'), glow: col('glow'), css });
  });
  return out;
}
const own = palettes(A('kit/src/main/kotlin/hu/vrg/mobile/kit/theme/Melyviz.kt'));
const kit = palettes(A('kit/src/main/kotlin/hu/vrg/mobile/kit/theme/KitTokens.kt'));
const ALL = [...own.filter(p => !p.id.startsWith('kit-')), ...kit];
const DEFAULT = 'melyviz';
const res = id => id.replace(/-/g, '_');

// ---- geometry ---------------------------------------------------------------------------------------------------
const nums = mark.match(/-?\d+(\.\d+)?/g).map(Number);
const xs = nums.filter((_, i) => i % 2 === 0), ys = nums.filter((_, i) => i % 2 === 1);
const box = { x: Math.min(...xs), y: Math.min(...ys), w: Math.max(...xs) - Math.min(...xs), h: Math.max(...ys) - Math.min(...ys) };
const f = v => +v.toFixed(3);

// the adaptive icon: 108 × 108, the launcher's mask keeps the middle 66 (a circle on most phones); the mark is tall,
// so its height sets the scale and it stands 56 units high in the middle
const S = 56 / box.h, TX = 54 - S * (box.x + box.w / 2), TY = 54 - S * (box.y + box.h / 2);

const HEAD = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by Mobile/catalogue/icon-gen.js from shared/varler-logo; do not edit. -->\n';

function iconVector(fill) {
  return HEAD + `<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:scaleX="${f(S)}" android:scaleY="${f(S)}" android:translateX="${f(TX)}" android:translateY="${f(TY)}">
        <path android:fillColor="${fill}" android:fillType="evenOdd"
            android:pathData="${mark}" />
    </group>
</vector>
`;
}

const files = {};
files[A('kit/src/main/res/drawable/vk_varler_mark.xml')] = HEAD + `<!-- The Varler mark alone (no wordmark), white: tint it where it is used (the home's watermark). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${f(box.w / 4)}dp" android:height="${f(box.h / 4)}dp"
    android:viewportWidth="${f(box.w)}" android:viewportHeight="${f(box.h)}">
    <group android:translateX="${f(-box.x)}" android:translateY="${f(-box.y)}">
        <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd"
            android:pathData="${mark}" />
    </group>
</vector>
`;
files[A('app/src/main/res/drawable/ic_launcher_mono.xml')] = iconVector('#FFFFFFFF');
for (const p of ALL) files[A(`app/src/main/res/drawable/ic_launcher_mark_${res(p.id)}.xml`)] = iconVector(p.glow);

files[A('app/src/main/res/values/launcher_icons.xml')] = HEAD + '<resources>\n' +
  ALL.map(p => `    <color name="launcher_bg_${res(p.id)}">${p.abyss}</color>   <!-- ${p.name} -->`).join('\n') + '\n</resources>\n';

const adaptive = id => HEAD + `<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/launcher_bg_${res(id)}" />
    <foreground android:drawable="@drawable/ic_launcher_mark_${res(id)}" />
    <monochrome android:drawable="@drawable/ic_launcher_mono" />
</adaptive-icon>
`;
files[A('app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml')] = adaptive(DEFAULT);
for (const p of ALL) files[A(`app/src/main/res/mipmap-anydpi-v26/ic_launcher_${res(p.id)}.xml`)] = adaptive(p.id);

// ---- the iPhone web app (WP M36): the same palettes and the same mark ------------------------------------------
const WEB = p => path.join(REPO, 'Mobile', 'web', p);
files[WEB('palettes.json')] = JSON.stringify({ about: 'Generated by Mobile/catalogue/icon-gen.js from the app\'s Kotlin palettes; do not edit.',
  default: DEFAULT, palettes: ALL.map(p => ({ id: p.id, name: p.name, light: p.light, colors: p.css })) }, null, 1) + '\n';
files[WEB('img/mark.svg')] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${f(box.x)} ${f(box.y)} ${f(box.w)} ${f(box.h)}"><!-- Varler mark (no wordmark), generated by Mobile/catalogue/icon-gen.js --><path fill="currentColor" fill-rule="evenodd" d="${mark}"/></svg>\n`;
files[WEB('js/mark.js')] = `// Generated by Mobile/catalogue/icon-gen.js: the Varler mark (no wordmark) as an SVG path, for inline drawing.\nexport const MARK = { d: ${JSON.stringify(mark)}, box: [${f(box.x)}, ${f(box.y)}, ${f(box.w)}, ${f(box.h)}] };\n`;

// ---- the manifest's aliases ----------------------------------------------------------------------------------
const MAN = A('app/src/main/AndroidManifest.xml');
const BEGIN = '<!-- launcher-aliases:begin (Mobile/catalogue/icon-gen.js) -->', END = '<!-- launcher-aliases:end -->';
const aliases = ALL.map(p => `        <activity-alias
            android:name=".Launcher_${res(p.id)}"
            android:targetActivity=".ShellActivity"
            android:enabled="${p.id === DEFAULT}"
            android:exported="true"
            android:icon="@mipmap/ic_launcher_${res(p.id)}"
            android:roundIcon="@mipmap/ic_launcher_${res(p.id)}">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>`).join('\n');
const man = fs.readFileSync(MAN, 'utf8');
const a = man.indexOf(BEGIN), b = man.indexOf(END);
if (a < 0 || b < a) { console.error('icon-gen: the launcher-aliases markers are missing from ' + MAN); process.exit(1); }
files[MAN] = man.slice(0, a + BEGIN.length) + '\n' + aliases + '\n        ' + man.slice(b);

// ---- write or check ---------------------------------------------------------------------------------------------
const check = process.argv.includes('--check');
let bad = 0;
for (const [file, text] of Object.entries(files)) {
  const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (cur === text) continue;
  if (check) { console.log('out of date: ' + path.relative(REPO, file)); bad++; }
  else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); console.log('wrote ' + path.relative(REPO, file)); }
}
if (check) { console.log(bad ? `icon-gen: ${bad} file(s) out of date; run node Mobile/catalogue/icon-gen.js` : `icon-gen: ${ALL.length} palettes, up to date`); process.exit(bad ? 1 : 0); }
console.log(`icon-gen: ${ALL.length} palettes (${ALL.map(p => p.id).join(', ')})`);
