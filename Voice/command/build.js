#!/usr/bin/env node
// build.js — commands.json → commands.js (window.VRGVoiceCommands) for the frame page, whose CSP (connect-src 'none') cannot fetch JSON.
//   node Voice/command/build.js           write it          node Voice/command/build.js --check   exit 1 when commands.js is stale
'use strict';
const fs = require('fs'), path = require('path');
const SRC = path.join(__dirname, 'commands.json'), OUT = path.join(__dirname, 'commands.js');

function render(json) {
  return '// GENERATED by Voice/command/build.js from commands.json — do not edit; change commands.json and run the build.\n' +
    'window.VRGVoiceCommands = ' + JSON.stringify(json, null, 1) + ';\n';
}
module.exports = { render, SRC, OUT };

if (require.main === module) {
  const text = render(JSON.parse(fs.readFileSync(SRC, 'utf8')));
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('Voice/command/commands.js is stale: run node Voice/command/build.js'); process.exit(1); }
    console.log('commands.js is current');
  } else { fs.writeFileSync(OUT, text); console.log('wrote ' + path.relative(process.cwd(), OUT)); }
}
