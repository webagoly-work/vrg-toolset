// VRG Stack — Kisokos 3D data for kisokos.html, the K layer's own page.
//
//   out/kisokos-data.js   window.KISOKOS = { core, rings, volumes, axes, terms, items, links, stats }
//
// Where the data comes from:
//   · the Kisokos sources through their own loader (Kisokos/kisokos.js): the map (core, axes, term nodes,
//     volumes), every card in full (the page shows it), and the outside knowledge bases with their byte size;
//   · the stack graph (the one the build just made, or out/stack.json) for each K node's vertical neighbours.
// The page turns bytes into cubes (cubeBytes, 1 KB = 1 cube) and grows the cube forms itself, deterministically,
// so this file carries the facts and not a layout.
// `--standalone <file>` also writes one self-contained page (data and the Mélyvíz css inlined), for sharing.
// Read-only on the sources; writes out/kisokos-data.js (and the standalone page) only.
'use strict';

const fs = require('fs');
const path = require('path');
const CFG = require('../config');
const X = require('./fsx');

const KL = () => { const f = path.join(__dirname, '..', '..', 'Kisokos', 'kisokos.js'); delete require.cache[require.resolve(f)]; return require(f); };

function build(graph) {
  const KM = KL(), K = KM.load(), VS = KM.VS, lines = K.cards.filter(c => c.kind === 'vonal');
  if (!graph) graph = X.readJson(path.join(CFG.out, 'stack.json'), null);
  const vols = K.map.volumes.map(v => ({ id: v.id, hu: v.hu, color: v.color, n: K.cards.filter(c => c.vol === v.id).length }));
  const items = [];
  for (const c of K.cards) {
    const { vol, kind, gid, file, bytes, cubes, place, title, aka, added, stock: _s, ...rest } = c;   // rest = the card's own fields
    delete rest.id;
    items.push({ id: 'card.' + gid, type: 'card', vol, kind, title, aka: aka || [], place, cubes, bytes, added, file, card: rest,
      stock: (c.stock || []).map(s => [s.vrg, s.name, s.rel, s.price, s.why]),
      ...(kind === 'vonal' ? { svg: VS.onePager(c, lines) } : kind === 'lampa' ? { svg: KM.LS.card(c) } : {}) });   // lines and lamp types carry their drawing
  }
  const stockCards = K.cards.filter(c => c.stock && c.stock.length).map(c => ['card.' + c.gid, c.stock.length]);
  for (const s of K.sources) items.push({ ...(s.id === 'keszlet' ? { stockCards } : {}), id: 'src.' + s.id, type: 'source', vol: s.volume, color: s.color, kind: 'tudásbázis', title: s.title, aka: [], place: s.place,
    cubes: s.cubes, bytes: s.bytes, added: '', file: s.paths.join(' · '), src: { sub: s.sub, why: s.why, paths: s.paths, files: s.files } });
  // vertical neighbours of each K node (what the rest of the stack says about it)
  const links = {};
  if (graph && Array.isArray(graph.nodes)) {
    const by = new Map(graph.nodes.map(n => [n.id, n]));
    const edges = (graph.edges || []).map(e => Array.isArray(e) ? { a: e[0], b: e[1], rel: e[2] } : e);
    for (const e of edges) for (const [x, y] of [[e.a, e.b], [e.b, e.a]]) {
      if (!x.startsWith('K:') || y.startsWith('K:')) continue;
      const n = by.get(y); if (!n) continue;
      const k = x.slice(2); (links[k] = links[k] || []);
      if (links[k].length < 8 && !links[k].some(l => l[0] === y)) links[k].push([y, n.title, n.layer, e.rel]);
    }
  }
  const coreCubes = items.filter(i => i.place.core).reduce((s, i) => s + i.cubes, 0);
  return {
    about: 'Generated by Stack/lib/kisokos.js from Kisokos/ — never edit by hand.',
    generated: new Date().toISOString(), cubeBytes: K.map.cubeBytes || 1024,
    core: K.map.core, rings: K.map.rings, volumes: vols,
    axes: K.map.axes.map(a => ({ n: a.n, hu: a.hu, q: a.q, A: a.A, B: a.B })),
    terms: K.terms.map(t => ({ id: t.id, axis: t.axis, pole: t.pole, ring: t.ring, title: t.title, desc: t.desc, vols: t.vols })),
    items, links,
    stats: { cards: K.cards.length, cubes: items.reduce((s, i) => s + i.cubes, 0), coreCubes, sources: K.sources.length, problems: KM.check(K).length },
  };
}

function write({ graph, standalone } = {}) {
  const data = build(graph);
  const js = '// generated by stack.js kisokos (Stack/lib/kisokos.js)\nwindow.KISOKOS = ' + JSON.stringify(data) + ';\n';
  fs.mkdirSync(CFG.out, { recursive: true });
  X.writeAtomic(path.join(CFG.out, 'kisokos-data.js'), js);
  let extra = '';
  if (standalone) {
    const root = path.join(__dirname, '..');
    let html = fs.readFileSync(path.join(root, 'kisokos.html'), 'utf8');
    const css = fs.readFileSync(path.join(root, '..', 'shared', 'melyviz.css'), 'utf8');
    const touch = fs.readFileSync(path.join(root, 'touch.js'), 'utf8');
    html = html.replace('<link rel="stylesheet" href="../shared/melyviz.css">', () => '<style>\n' + css + '\n</style>')
      .replace('<script src="touch.js"></script>', () => '<script>\n' + touch + '\n</script>')
      .replace('<script src="out/kisokos-data.js"></script>', () => '<script>\n' + js.replace(/<\/script/gi, '<\\/script') + '</script>');
    fs.writeFileSync(standalone, html);
    extra = ` + standalone ${standalone}`;
  }
  return { msg: `kisokos: ${data.stats.cards} cards, ${data.items.length - data.stats.cards} knowledge bases, ${data.stats.cubes} cubes (${data.stats.coreCubes} in the core) → out/kisokos-data.js${extra}`, data };
}

module.exports = { build, write };
