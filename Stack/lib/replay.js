// VRG Stack — data for the replay page (replay.html, "Visszajátszás").
//
//   out/replay/index.js     window.REPLAY_INDEX = [ one row per session ]
//   out/replay/<sid8>.js    REPLAY_LOAD('<sid8>', { steps, nodes, adj })
// A page opened from file:// cannot fetch JSON, so the data is script files the page loads one at
// a time. Each session file carries its steps and the small piece of the stack they touch: the
// touched nodes plus their strongest neighbours, with the links between them, so the page can run
// spreading activation (lib/activation.js) without loading the whole stack.
// Incremental: a session file is written again only when its recording changed.
'use strict';

const fs = require('fs');
const path = require('path');
const CFG = require('../config');
const X = require('./fsx');
const { clip } = require('./common');

const DIR = path.join(CFG.out, 'replay');
const NEIGH = 4; // neighbours kept per touched node

function exportAll(index, g, readRecording) {
  fs.mkdirSync(DIR, { recursive: true });
  const stamps = X.readJson(path.join(DIR, 'stamps.json'), {});
  const rows = []; let written = 0;
  const rank = id => (g.byId.get(id) || {}).rank || 0;
  for (const [sid8, s] of Object.entries(index.sessions)) {
    if (s.steps < 3) continue;
    rows.push({ sid: sid8, title: s.title, project: s.project, start: s.start, end: s.end, steps: s.steps, prompts: s.prompts, commits: s.commits.length, subagents: s.subagents,
      tools: Object.entries(s.tools).sort((a, b) => b[1] - a[1]).slice(0, 5) });
    const file = path.join(DIR, sid8 + '.js');
    const key = index.version + ':' + s.stamp; // a new recorder version redoes every file
    if (stamps[sid8] === key && fs.existsSync(file)) continue;
    const steps = readRecording(sid8);
    const touched = new Set(); for (const st of steps) for (const id of st.nodes) if (g.byId.has(id)) touched.add(id);
    const keep = new Set(touched);
    for (const id of touched) g.nb(id).filter(x => x.v !== 2).sort((a, b) => rank(b.id) - rank(a.id)).slice(0, NEIGH).forEach(x => keep.add(x.id));
    const nodes = {};
    for (const id of keep) { const n = g.byId.get(id); nodes[id] = [n.layer, clip(n.title, 70), n.kind]; }
    const adj = {};
    for (const id of keep) { const nb = [...new Set(g.nb(id).filter(x => x.v !== 2 && keep.has(x.id)).map(x => x.id))]; if (nb.length) adj[id] = nb; }
    const lean = steps.map(st => [st.t, st.span, st.tool || '', st.actor, (st.paths || []).slice(0, 3), st.nodes.filter(id => keep.has(id)).slice(0, 12), st.ok === false ? 0 : 1, clip(st.text || '', 160), st.tok ? st.tok.out : 0]);
    X.writeAtomic(file, `REPLAY_LOAD(${JSON.stringify(sid8)}, ${JSON.stringify({ steps: lean, nodes, adj })});\n`);
    stamps[sid8] = key; written++;
  }
  rows.sort((a, b) => (b.start || '').localeCompare(a.start || ''));
  X.writeAtomic(path.join(DIR, 'index.js'), `// generated by stack.js build\nwindow.REPLAY_INDEX = ${JSON.stringify(rows)};\n`);
  X.writeAtomic(path.join(DIR, 'stamps.json'), JSON.stringify(stamps));
  return { sessions: rows.length, written };
}

module.exports = { exportAll, DIR };
