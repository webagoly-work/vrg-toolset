// VRG Stack — the drift report: what is unfinished, waiting, quiet or disconnected,
// found by reading across the layers rather than inside one.
'use strict';

const C = require('./common');
const clip = C.clip;

module.exports = function drift(graph, full, ctx) {
  const today = new Date().toISOString().slice(0, 10);
  const days = d => d ? Math.round((Date.parse(today) - Date.parse(d)) / 864e5) : 999;
  const byId = new Map(graph.nodes.map(n => [n.id, n]));
  const nb = new Map(); // id → [{id, rel, v}]
  for (const e of graph.edges) for (const [x, y] of [[e.a, e.b], [e.b, e.a]]) { if (!nb.has(x)) nb.set(x, []); nb.get(x).push({ id: y, rel: e.rel, v: e.v }); }
  const out = [`# VRG Stack — drift report`, ``, `${today}. Generated by build.js; every item names a node id: \`stack.js node <id>\` shows its links.`, ``];

  /* 1. repo state */
  try {
    const st = C.git('status', '--porcelain').split('\n').filter(Boolean);
    const per = {}; for (const l of st) { const p = l.slice(3).replace(/"/g, ''); const top = p.split('/')[0]; per[top] = (per[top] || 0) + 1; }
    let ahead = '?'; try { ahead = C.git('rev-list', '--count', 'origin/main..main').trim(); } catch {}
    out.push(`## 1. Repo: uncommitted and unpushed`, ``, `- main is **${ahead}** commits ahead of origin/main.`,
      `- ${st.length} changed or new files not committed: ` + Object.entries(per).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(', ') + '.', ``);
  } catch (e) { out.push(`## 1. Repo`, ``, `git status failed: ${e.message}`, ``); }

  /* 2. dev lines that are open but quiet */
  const lines = graph.nodes.filter(n => n.layer === 'L' && n.kind === 'line');
  const lastSession = id => (nb.get(id) || []).filter(x => x.rel === 'on-line').map(x => byId.get(x.id).t).sort().pop() || '';
  const open = lines.filter(n => ['active', 'waiting'].includes(n.state)).map(n => ({ n, last: lastSession(n.id) || n.t }))
    .sort((a, b) => a.last.localeCompare(b.last));
  out.push(`## 2. Open dev lines, quietest first`, ``, `| Line | State | Last session | Days quiet | Next step |`, `|---|---|---|---|---|`,
    ...open.map(({ n, last }) => `| ${n.id} ${clip(n.title, 40)} | ${n.state} | ${last || '—'} | ${days(last) >= 5 ? '⚠ ' : ''}${days(last)} | ${clip(full.get(n.id).extra.nextStep, 90)} |`), ``);

  /* 3. open decisions */
  const decs = graph.nodes.filter(n => n.kind === 'decision' && n.state.startsWith('open'));
  const byFile = {}; for (const d of decs) { const f = full.get(d.id).extra.path; (byFile[f] = byFile[f] || []).push(d.id.slice(2)); }
  out.push(`## 3. Decisions that look unanswered (≈ loose parse; check the file)`, ``, `${decs.length} of ${graph.nodes.filter(n => n.kind === 'decision').length} decisions; ${graph.nodes.filter(n => n.state === 'default A').length} more count as A only because their file says "Unanswered = A" — worth one look.`, ``,
    ...Object.entries(byFile).sort((a, b) => b[1].length - a[1].length).map(([f, ids]) => `- \`${f}\`: ${ids.join(', ')}`), ``);

  /* 4. features in development with no recent activity below them */
  const dev = graph.nodes.filter(n => n.layer === 'F' && n.tier === 3);
  const activity = id => { let last = ''; for (const x of nb.get(id) || []) { const m = byId.get(x.id); if (x.v && (m.layer === 'R' || m.layer === 'L') && m.t > last) last = m.t; }
    for (const ent of byId.get(id).ent) for (const n of graph.nodes) if ((n.layer === 'R' || n.layer === 'L') && n.ent.includes(ent) && n.t > last) last = n.t; return last; };
  out.push(`## 4. Features "in development" and their last commit or session`, ``, `| Feature | Last activity | Days |`, `|---|---|---|`,
    ...dev.map(n => ({ n, a: activity(n.id) })).sort((a, b) => a.a.localeCompare(b.a)).map(({ n, a }) => `| ${n.id} ${clip(n.title, 50)} | ${a || 'none found'} | ${days(a) >= 7 ? '⚠ ' : ''}${a ? days(a) : '—'} |`), ``);

  /* 5. Globe signals */
  const sig = graph.nodes.filter(n => n.kind.startsWith('signal/'));
  const stages = {}; for (const s of sig) stages[s.state] = (stages[s.state] || 0) + 1;
  out.push(`## 5. Data Globe signals not ruled`, ``, `${sig.length} signals: ` + Object.entries(stages).map(([k, v]) => `${k} ${v}`).join(', ') + '. Ruling stays with the Founder (Solomon rule).', ``,
    ...sig.filter(s => s.kind === 'signal/contradiction').map(s => `- ${s.id} ${clip(s.title, 80)} [${s.state}]`), ``);

  /* 6. disconnected */
  const lonely = (pred) => graph.nodes.filter(n => pred(n) && !n.deg.v);
  const sect = (title, list, k = 30) => [`**${title}: ${list.length}**` + (list.length ? ' — ' + list.slice(0, k).map(n => `${n.id}`).join(', ') + (list.length > k ? ' …' : '') : ''), ''];
  out.push(`## 6. Nodes with no vertical link (they float on their own layer)`, ``,
    ...sect('Features', lonely(n => n.layer === 'F')),
    ...sect('Dev lines', lonely(n => n.layer === 'L' && n.kind === 'line')),
    ...sect('Memory notes', lonely(n => n.kind.startsWith('memory/'))),
    ...sect('Briefs + agents', lonely(n => n.kind === 'brief' || n.kind === 'agent')),
    ...sect('Ideas', lonely(n => n.layer === 'I')),
    ...sect('Code modules (top level)', lonely(n => n.kind === 'module')));

  /* 7. pillar gaps: a thing that exists on one layer but is missing where it should be */
  const gap = [];
  for (const e of graph.entities) {
    const has = l => (e.per[l] || 0) > 0;
    const miss = [];
    if ((has('C') || has('R')) && !has('F')) miss.push('no Featured entry (built but not on the Dashboard)');
    if (has('F') && !has('L')) miss.push('no DevLog line');
    if (has('F') && !has('A')) miss.push('no brief / memory / agent');
    if (has('L') && !has('G') && has('C')) miss.push('no document in the Globe');
    if (miss.length) gap.push(`- **${e.name}** (${Object.entries(e.per).map(([l, c]) => l + c).join(' ')}): ${miss.join('; ')}`);
  }
  out.push(`## 7. Pillar gaps`, ``, ...(gap.length ? gap : ['none']), ``);

  /* 8. joins that failed */
  out.push(`## 8. Joins that failed`, ``, `- ${ctx.unresolved} mentions pointed at a key no node owns (mostly folders outside every layer).`,
    `- ${ctx.dangling.length} source links point at a node that does not exist` + (ctx.dangling.length ? ': ' + ctx.dangling.slice(0, 12).map(e => `${e.a}→${e.b} (${e.rel})`).join(', ') : '') + '.', ``);
  return out.join('\n');
};
