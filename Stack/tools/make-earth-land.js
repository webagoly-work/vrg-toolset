// Builds earth-land.js (the land mask for the Holo page's Föld form) from Natural Earth 1:110m land
// (public domain, naturalearthdata.com; GeoJSON from github.com/nvkelso/natural-earth-vector).
// Usage: node tools/make-earth-land.js <ne_110m_land.geojson>
// Output: a 720 × 360 bit raster (0.5°), row 0 = 90° N, column 0 = 180° W, base64.
'use strict';
const fs = require('fs'), path = require('path');
const src = process.argv[2];
if (!src) { console.error('usage: node tools/make-earth-land.js <ne_110m_land.geojson>'); process.exit(1); }
const W = 720, H = 360, gj = JSON.parse(fs.readFileSync(src, 'utf8'));
const rings = [];
for (const f of gj.features) {
  const g = f.geometry, polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  for (const p of polys) for (const r of p) rings.push(r);
}
const bits = new Uint8Array(W * H / 8);
for (let y = 0; y < H; y++) {
  const lat = 90 - (y + 0.5) * 180 / H, xs = [];
  for (const r of rings) for (let i = 0, j = r.length - 1; i < r.length; j = i++) {   // even-odd scanline crossings
    const [x1, y1] = r[i], [x2, y2] = r[j];
    if ((y1 > lat) !== (y2 > lat)) xs.push(x1 + (lat - y1) * (x2 - x1) / (y2 - y1));
  }
  xs.sort((a, b) => a - b);
  for (let k = 0; k + 1 < xs.length; k += 2) {
    const a = Math.max(0, Math.ceil((xs[k] + 180) * W / 360 - 0.5)), b = Math.min(W - 1, Math.floor((xs[k + 1] + 180) * W / 360 - 0.5));
    for (let x = a; x <= b; x++) { const i = y * W + x; bits[i >> 3] |= 1 << (i & 7); }
  }
}
let land = 0; for (let i = 0; i < W * H; i++) if (bits[i >> 3] >> (i & 7) & 1) land++;
const out = path.join(__dirname, '..', 'earth-land.js');
fs.writeFileSync(out, `// generated by tools/make-earth-land.js from Natural Earth 1:110m land (public domain). ${W}×${H} bits, row 0 = 90°N, col 0 = 180°W.\n` +
  `window.EARTH_LAND = { w: ${W}, h: ${H}, bits: '${Buffer.from(bits).toString('base64')}' };\n`);
console.log(`earth-land.js: ${W}×${H}, land ${(100 * land / (W * H)).toFixed(1)} % of cells`);
