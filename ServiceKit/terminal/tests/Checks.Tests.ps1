# Pester 5 tests for the pure parts of the checks and recommend.ps1.
BeforeAll {
    $TermDir = Split-Path -Parent $PSScriptRoot
    . (Join-Path $TermDir 'lib.ps1')
    . (Join-Path $TermDir 'detect.ps1')
    . (Join-Path $TermDir 'recommend.ps1')
    . (Join-Path $TermDir 'checks\run.ps1')
    $Cat = @{ packages = @(
        @{ id = 'portablegit'; name = 'Git'; sizeMB = 60 }, @{ id = 'node'; name = 'Node.js'; sizeMB = 30 },
        @{ id = 'claude-code'; name = 'Claude Code'; sizeMB = 60 }, @{ id = 'virtualbox'; name = 'VirtualBox'; sizeMB = 110 }) }
    function R($Tier, $Items) { return @{ tier = $Tier; items = $Items } }
}

Describe 'Test-TermTlsIntercepted' {
    It 'names the product that re-signs HTTPS' {
        $r = Test-TermTlsIntercepted 'CN=Avast Web/Mail Shield Root, O=Avast Web/Mail Shield, OU=generated by Avast Antivirus'
        $r['status'] | Should -Be 'intercepted'
        $r['product'] | Should -Be 'Avast'
    }
    It 'accepts public CAs' {
        (Test-TermTlsIntercepted 'CN=WE1, O=Google Trust Services, C=US')['status'] | Should -Be 'public'
        (Test-TermTlsIntercepted 'CN=Sectigo ECC Domain Validation Secure Server CA, O=Sectigo Limited')['status'] | Should -Be 'public'
        (Test-TermTlsIntercepted 'CN=R11, O=Let''s Encrypt, C=US')['status'] | Should -Be 'public'
    }
    It 'flags an unknown issuer and no certificate' {
        (Test-TermTlsIntercepted 'CN=Corp Root CA')['status'] | Should -Be 'unknown'
        (Test-TermTlsIntercepted '')['status'] | Should -Be 'none'
    }
}

Describe 'Get-TermRecommendations' {
    It 'suggests catalog packages for missing tools, with size, and skips ones the catalog lacks' {
        $res = @((R 'T1' @((New-TermItem 'git' '' 'missing'), (New-TermItem 'gh' '' 'missing'))))
        $rec = @(Get-TermRecommendations $res $Cat @{} @() 'K')
        $rec.Count | Should -Be 1
        $rec[0]['action'] | Should -Be 'install'
        $rec[0]['pkg'] | Should -Be 'portablegit'
        $rec[0]['sizeMB'] | Should -Be 60
    }
    It 'does not suggest what the kit already installed' {
        $res = @((R 'T1' @((New-TermItem 'git' '' 'missing'))))
        @(Get-TermRecommendations $res $Cat @{ portablegit = @{} } @() 'K').Count | Should -Be 0
    }
    It 'suggests an update below the minimum version' {
        $res = @((R 'T1' @((New-TermItem 'node' 'v16.20.0' 'ok' '' @{ version = '16.20.0' }))))
        (@(Get-TermRecommendations $res $Cat @{} @() 'K'))[0]['action'] | Should -Be 'update'
    }
    It 'TLS interception gives the NODE_EXTRA_CA_CERTS hint' {
        $res = @((R 'T2' @((New-TermItem 'tls' 'x' 'bad' '' @{ product = 'Avast' }))))
        (@(Get-TermRecommendations $res $Cat @{} @() 'K'))[0]['reason'] | Should -Match 'NODE_EXTRA_CA_CERTS'
    }
    It 'Home edition points to VirtualBox; a disabled Sandbox gives the enable command' {
        $home1 = @((R 'T4' @((New-TermItem 'edition' 'Windows 11 Home' 'warn' '' @{ home = $true }))))
        (@(Get-TermRecommendations $home1 $Cat @{} @() 'K'))[0]['pkg'] | Should -Be 'virtualbox'
        $pro = @((R 'T4' @((New-TermItem 'edition' 'Windows 11 Pro' 'ok' '' @{ home = $false }), (New-TermItem 'sandbox' 'disabled' 'warn' '' @{ state = 'disabled' }))))
        (@(Get-TermRecommendations $pro $Cat @{} @() 'K'))[0]['command'] | Should -Match 'Containers-DisposableClientVM'
    }
    It 'two Claude installs give an uninstall suggestion that is only listed' {
        $res = @((R 'T2' @((New-TermItem 'claude' 'x' 'ok' '' @{ sources = @('npm', 'native') }))))
        $r = (@(Get-TermRecommendations $res $Cat @{} @() 'K'))[0]
        $r['action'] | Should -Be 'uninstall'
        Format-TermRecommendation $r | Should -Match 'npm uninstall'
    }
    It 'a ledger row whose files are gone is offered for forgetting' {
        $r = @(Get-TermRecommendations @() $Cat @{} @(@{ pkg = 'ripgrep'; paths = @('tools\ripgrep-gone-xyz') }) $TestDrive)
        $r[0]['pkg'] | Should -Be 'ripgrep'
    }
}

Describe 'Compare-TermVersion' {
    It 'compares loose version strings' {
        Compare-TermVersion 'v18.19.1' '18.0' | Should -BeGreaterThan 0
        Compare-TermVersion 'git version 2.25.1.windows.1' '2.30' | Should -BeLessThan 0
        Compare-TermVersion 'none' '1.0' | Should -BeNullOrEmpty
    }
}

Describe 'Format-TermReportHtml' {
    It 'writes both languages and escapes values' {
        $h = Format-TermReportHtml @((R 'T0' @((New-TermItem 'os' '<b>x</b>' 'info')))) @() 'stamp'
        $h | Should -Match '&lt;b&gt;'
        $h | Should -Match 'class="en"'
    }
}
