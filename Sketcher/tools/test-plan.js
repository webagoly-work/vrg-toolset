#!/usr/bin/env node
// Sketcher/tools/test-plan.js — the two-phone test plan of the VRG Sketcher (the Founder, 2026-11-20: "then we will start
// testing with two connected phones at the same time"). Reads the "Telefonon ellenőrizni" list of every Sketcher work
// package (docs/mobile/WP/M<nn>.md), splits the packages between phone A and phone B so both run at once, adds the steps
// that need both phones or the PC, and writes:
//   docs/sketcher/TEST-2PHONES.md   the plan to read
//   docs/sketcher/test-2phones.json the same as data (the shared checklist page is built from it)
//
//   node Sketcher/tools/test-plan.js           write both
//   node Sketcher/tools/test-plan.js --check   exit 1 when either is stale (a WP's list changed)
'use strict';
const fs = require('fs'), path = require('path');
const REPO = path.join(__dirname, '..', '..');
const WP = n => path.join(REPO, 'docs', 'mobile', 'WP', 'M' + n + '.md');

// Phone A: the drawing and the conversation. Phone B: the camera and the place. Balanced by step count.
const PLAN = {
  A: { name: 'A telefon — rajz és beszélgetés', sub: 'a tulajdonos telefonja (párosított PC, Átadás)', wps: [24, 26, 27, 28, 47, 49, 50] },
  B: { name: 'B telefon — kamera és helyszín', sub: 'a második telefon (Eszközök: jóváhagyva)', wps: [25, 29, 46, 30, 48, 31, 51] },
};
const PREP = [
  'Mindkét telefonon a legújabb kiadás (Beállítások → Frissítés); a Névjegy ugyanazt a verziót mutatja.',
  'A B telefon be van engedve (Eszközök: QR vagy Eszközkód, M35); mindkettőn nyílik a VRG Sketcher a kezdőlap nagy csempéjéről.',
  'A PC-n START fut; a relay `--ports`-szal (`Mobile\\mobile.cmd relay`), a VRG Térkép szerver (START → H) és az Asztal Sketcher oldala (START P → S) elérhető.',
  'Mindkét telefonon új felmérés „Teszt A” / „Teszt B” néven — ügyféladat nélkül.',
];
const CROSS = [
  { id: 'X1', text: 'A: Rendezés → Küldés PC-re. A PC-n az Asztal Sketcher oldalán a csomag megnyílik: Munkakör lap, kérdések, fotók, helyszín, szobánkénti igények ugyanazok, mint a telefonon.' },
  { id: 'X2', text: 'A csomagot a Plannerben is nyisd meg (⌘K → Vázlat): a szobák, pontok, a ≈ jelölt méretek és a „Felmérés: munkakör lap” megvan.' },
  { id: 'X3', text: 'B: Rendezés → Küldés PC-re a fotókkal: a PC táblán a képek a felmérés nevével, a jelöltek `_jel.jpg`-vel; a GPS csak ott van benne, ahol meghagytad.' },
  { id: 'X4', text: 'B: ⚙ → Variánsok → ＋ Új variáns kérése két fotóval → a kérés a PC táblán; benne nincs ügyfélnév, cím, személyes fotó.' },
  { id: 'X5', text: 'Mindkét telefonon egyszerre: a VRG Térkép PC nélkül is nyílik (mobilnet), a másik telefon felmérése nem látszik (minden telefon csak a sajátját).' },
  { id: 'X6', text: 'A ⟳ Frissítés a main ágról (Variánsok) mindkét telefonon ugyanazt a variánslistát adja (Fürdő, E-autó, Ipari telephely).' },
  { id: 'X7', text: 'Csere: A és B felmérést cserél Átadáson át (A küldi a PC-re, B a PC tábláról megnyitja a Desktopon) — az eredmény ugyanaz, mint A-n.' },
];

function steps(n) {
  const f = WP(n);
  if (!fs.existsSync(f)) return null;
  const md = fs.readFileSync(f, 'utf8');
  const title = md.split('\n')[0].replace(/^#\s*/, '').trim();
  const m = md.match(/^## Telefonon ellenőrizni[^\n]*\n([\s\S]*?)(?=^## |\s*$(?![\s\S]))/m);
  if (!m) return { n, title, items: [] };
  const items = [];
  for (const line of m[1].split('\n')) {
    const s = line.match(/^\s*(\d+[a-z]?)\.\s+(.*)$/);
    if (s) items.push({ id: 'M' + n + '.' + s[1], text: s[2].trim() });
    else if (items.length && line.trim()) items[items.length - 1].text += ' ' + line.trim();
  }
  return { n, title, items };
}

function build() {
  const phones = {};
  for (const [k, p] of Object.entries(PLAN)) {
    const wps = p.wps.map(steps).filter(Boolean);
    phones[k] = { name: p.name, sub: p.sub, wps, count: wps.reduce((a, w) => a + w.items.length, 0) };
  }
  return { kind: 'vrg-sketcher-test-plan', v: 1, prep: PREP, phones, cross: CROSS };
}

function md(d) {
  const L = ['# VRG Sketcher — kéttelefonos teszt', '',
    '*Generated by `node Sketcher/tools/test-plan.js` from the work packages\' "Telefonon ellenőrizni" lists; edit those, not this.*', '',
    'A két telefon **egyszerre** dolgozik: az A a rajzot és a beszélgetést, a B a kamerát és a helyszínt teszteli. A végén a közös lépések (X) a PC-vel. Ami nem úgy megy, mint a leírás: a lépés száma + egy mondat + képernyőkép, a többi lépés megy tovább.', '',
    '## 0. Előkészület (mindkét telefon)', ''];
  d.prep.forEach((t, i) => L.push((i + 1) + '. ' + t));
  for (const [k, p] of Object.entries(d.phones)) {
    L.push('', '## ' + p.name + ' (' + p.count + ' lépés)', '', '*' + p.sub + '*');
    for (const w of p.wps) {
      L.push('', '### ' + w.title, '');
      w.items.forEach(s => L.push('- [ ] **' + s.id + '** ' + s.text));
    }
  }
  L.push('', '## X. Közös lépések (mindkét telefon + PC)', '');
  d.cross.forEach(s => L.push('- [ ] **' + s.id + '** ' + s.text));
  return L.join('\n') + '\n';
}

const d = build(), json = JSON.stringify(d, null, 1) + '\n', text = md(d);
const outMd = path.join(REPO, 'docs', 'sketcher', 'TEST-2PHONES.md'), outJs = path.join(REPO, 'docs', 'sketcher', 'test-2phones.json');
if (process.argv.includes('--check')) {
  const stale = [[outMd, text], [outJs, json]].filter(([f, t]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== t);
  if (stale.length) { console.log('stale: ' + stale.map(s => path.relative(REPO, s[0])).join(', ') + ' — run node Sketcher/tools/test-plan.js'); process.exit(1); }
  console.log('test plan up to date (A ' + d.phones.A.count + ', B ' + d.phones.B.count + ', közös ' + d.cross.length + ')');
} else {
  fs.writeFileSync(outMd, text); fs.writeFileSync(outJs, json);
  console.log('wrote docs/sketcher/TEST-2PHONES.md + test-2phones.json (A ' + d.phones.A.count + ', B ' + d.phones.B.count + ', közös ' + d.cross.length + ')');
}
