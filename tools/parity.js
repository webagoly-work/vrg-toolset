#!/usr/bin/env node
// parity.js — one feature list for both apps (WP-50 / M46): launcher/vrg-parity.json against the VRG Desktop's catalog
// (launcher/vrg-catalog.json) and VRG Mobile's catalogue (Catalogue.ALL in Mobile/android/kit-core/.../Feature.kt).
//
//   node tools/parity.js            check, then write Dashboard/config/phone-cards.json and the table in docs/mobile/PARITY.md
//   node tools/parity.js --check    exit 1 when the list is wrong or a written file is out of date (gates a commit)
//
// Every Desktop unit (categories aside) and every phone feature must have exactly one line, and every line must point at
// something real: a phone feature or frame part, a Desktop unit, a port, a queued work package. Mobile/catalogue/desk-gen.js
// reads the `desk` half for the phone; the Desktop reads phone-cards.json for the phone features it shows as grey / gap tiles.
// Console output stays ASCII.
'use strict';
const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');
const PARITY = path.join(REPO, 'launcher', 'vrg-parity.json');
const CATALOG = path.join(REPO, 'launcher', 'vrg-catalog.json');
const FEATURES = path.join(REPO, 'Mobile', 'android', 'kit-core', 'src', 'main', 'kotlin', 'hu', 'vrg', 'mobile', 'core', 'Feature.kt');
const CARDS = path.join(REPO, 'Dashboard', 'config', 'phone-cards.json');
const DOC = path.join(REPO, 'docs', 'mobile', 'PARITY.md');
const BEGIN = '<!-- parity:begin (GENERATED by tools/parity.js from launcher/vrg-parity.json; do not edit by hand) -->';
const END = '<!-- parity:end -->';

const FRAME = ['desk', 'kompakt', 'kommand', 'browser'];          // the phone's Asztal frame parts a unit may open
const DESK_STATES = ['native', 'webapp', 'pc', 'grey', 'gap'];     // a Desktop unit on the phone
const PHONE_STATES = ['full', 'grey', 'gap'];                       // a phone feature on the Desktop
const ascii = s => String(s).normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^\x20-\x7e]/g, '?');

// Catalogue.ALL from Feature.kt: FeatureInfo("id", "title", "blurb", "glyph", Group.X, Stage.Y, "wp", …), in the ALL order
function phoneFeatures() {
  const s = fs.readFileSync(FEATURES, 'utf8');
  const str = '"((?:[^"\\\\]|\\\\.)*)"';
  const re = new RegExp('val\\s+(\\w+)\\s*=\\s*FeatureInfo\\(\\s*' + [str, str, str, str].join(',\\s*') + ',\\s*Group\\.(\\w+),\\s*Stage\\.(\\w+),\\s*' + str, 'g');
  const un = t => t.replace(/\\(.)/g, '$1');
  const byVal = new Map();
  for (const m of s.matchAll(re)) byVal.set(m[1], { id: un(m[2]), hu: un(m[3]), about: un(m[4]), glyph: un(m[5]), group: m[6], stage: m[7], wp: un(m[8]) });
  const all = /val\s+ALL\s*:\s*List<FeatureInfo>\s*=\s*listOf\(([\s\S]*?)\)/.exec(s);
  if (!all) throw new Error('parity: Catalogue.ALL not found in Feature.kt');
  const names = all[1].split(/[\s,]+/).filter(Boolean);
  return names.map(n => { const f = byVal.get(n); if (!f) throw new Error('parity: Catalogue.ALL names ' + n + ', which Feature.kt does not define as FeatureInfo'); return f; });
}

function load() {
  const parity = JSON.parse(fs.readFileSync(PARITY, 'utf8'));
  const cat = JSON.parse(fs.readFileSync(CATALOG, 'utf8'));
  const units = cat.items.filter(i => i.type !== 'category');
  return { parity, cat, units, feats: phoneFeatures() };
}

function check({ parity, units, feats }) {
  const err = [];
  const unitIds = new Set(units.map(u => u.id));
  const featIds = new Set(feats.map(f => f.id));
  const queue = parity.queue || {};
  const used = new Set();
  const desk = parity.desk || {}, phone = parity.phone || {};
  const wpOk = (where, e, side) => {
    if (!e.wp) err.push(where + ': gap without wp');
    else if (!queue[e.wp]) err.push(where + ': wp ' + e.wp + ' is not in queue');
    else if (queue[e.wp].side !== side) err.push(where + ': wp ' + e.wp + ' is a ' + queue[e.wp].side + ' work package, not ' + side);
    else used.add(e.wp);
  };

  for (const u of units) if (!desk[u.id]) err.push('desk: Desktop unit "' + u.id + '" (' + u.title.hu + ') has no line: how is it on the phone?');
  for (const [id, e] of Object.entries(desk)) {
    const w = 'desk.' + id;
    if (!unitIds.has(id)) { err.push(w + ': not a Desktop unit (any more)'); continue; }
    if (!DESK_STATES.includes(e.phone)) { err.push(w + ': phone must be one of ' + DESK_STATES.join('/')); continue; }
    if (['native', 'webapp', 'pc'].includes(e.phone) && !e.to) err.push(w + ': ' + e.phone + ' without to');
    if (e.phone === 'native' && e.to && !FRAME.includes(e.to) && !featIds.has(e.to) && !/^url:https:\/\/\S+$/.test(e.to)) err.push(w + ': native to "' + e.to + '" is no phone feature, frame part or url:https://');
    if (e.phone === 'pc' && e.to && !/^port:\d{2,5}$/.test(e.to) && !featIds.has(e.to)) err.push(w + ': pc to "' + e.to + '" is no port:<n> or phone feature');
    if (e.phone === 'webapp' && e.to && !/^[a-z0-9-]+$/.test(e.to)) err.push(w + ': webapp to "' + e.to + '" is no app id');
    if (['grey', 'gap'].includes(e.phone) && !e.about) err.push(w + ': ' + e.phone + ' without about (what the unit is, shown on the phone)');
    if (e.phone === 'grey' && !e.why) err.push(w + ': grey without why');
    if (e.phone === 'gap') { if (!e.plan) err.push(w + ': gap without plan'); wpOk(w, e, 'phone'); }
  }

  for (const f of feats) if (!phone[f.id]) err.push('phone: phone feature "' + f.id + '" (' + f.hu + ') has no line: how is it on the Desktop?');
  for (const [id, e] of Object.entries(phone)) {
    const w = 'phone.' + id;
    if (!featIds.has(id)) { err.push(w + ': not a phone feature (any more)'); continue; }
    if (!PHONE_STATES.includes(e.desk)) { err.push(w + ': desk must be one of ' + PHONE_STATES.join('/')); continue; }
    if (e.desk === 'full' && !unitIds.has(e.to)) err.push(w + ': full to "' + e.to + '" is no Desktop unit');
    if (e.desk === 'grey' && !e.why) err.push(w + ': grey without why');
    if (e.desk === 'gap') { if (!e.plan) err.push(w + ': gap without plan'); wpOk(w, e, 'desktop'); }
  }
  for (const id of Object.keys(queue)) if (!used.has(id)) err.push('queue.' + id + ': no line uses it');
  return err;
}

// the Desktop's phone tiles: every phone feature that is grey or gap on the Desktop, in Catalogue.ALL order
function cards({ parity, feats }) {
  const out = [];
  for (const f of feats) {
    const e = parity.phone[f.id];
    if (!e || e.desk === 'full') continue;
    const c = { id: 'phone:' + f.id, feature: f.id, hu: f.hu, glyph: f.glyph, about: f.about, stage: f.stage.toLowerCase(), mobileWp: f.wp, state: e.desk };
    if (e.desk === 'grey') c.why = e.why;
    else { c.plan = e.plan; c.wp = e.wp; c.wpHu = parity.queue[e.wp].hu; }
    out.push(c);
  }
  return JSON.stringify({ about: 'GENERATED by tools/parity.js from launcher/vrg-parity.json and Mobile Feature.kt — do not edit by hand. The phone features the VRG Desktop shows as tiles of their own: grey = no sense on a PC (the description only), gap = it is being built for the Desktop (the description and the work package).', cards: out }, null, 1) + '\n';
}

const cell = s => String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const LV = { user: 'user', dev: 'dev', all: 'all' };
const PH = { native: 'native', webapp: 'webapp', pc: 'pc', grey: '**szürke**', gap: 'hiány' };
const DK = { full: 'teljes', grey: '**szürke**', gap: 'hiány' };

function table({ parity, units, feats }) {
  const L = [BEGIN, ''];
  const n = (o, k) => Object.values(o).filter(e => (e.phone || e.desk) === k).length;
  L.push(`**Asztal → telefon:** ${units.length} egység: native ${n(parity.desk, 'native')}, webapp ${n(parity.desk, 'webapp')}, pc ${n(parity.desk, 'pc')}, szürke ${n(parity.desk, 'grey')}, hiány ${n(parity.desk, 'gap')}.  `);
  L.push(`**Telefon → Asztal:** ${feats.length} funkció: teljes ${n(parity.phone, 'full')}, szürke ${n(parity.phone, 'grey')}, hiány ${n(parity.phone, 'gap')}.`, '');
  L.push('### 1. Az Asztal egységei a telefonon', '');
  L.push('| # | Egység (id) | Név | Szint | A telefonon | Hová / miért / WP |', '|---|---|---|---|---|---|');
  units.forEach((u, i) => {
    const e = parity.desk[u.id] || {};
    const what = e.phone === 'grey' ? e.why : e.phone === 'gap' ? e.wp + ': ' + e.plan : '`' + e.to + '`';
    L.push(`| ${i + 1} | \`${u.id}\` | ${cell(u.title.hu)} | ${LV[u.level] || u.level} | ${PH[e.phone] || '?'} | ${cell(what)} |`);
  });
  L.push('', '### 2. A telefon funkciói az Asztalon', '');
  L.push('| # | Funkció (id) | Név | Mobil WP | Az Asztalon | Hová / miért / WP |', '|---|---|---|---|---|---|');
  feats.forEach((f, i) => {
    const e = parity.phone[f.id] || {};
    const what = e.desk === 'grey' ? e.why : e.desk === 'gap' ? e.wp + ': ' + e.plan : '`' + e.to + '`';
    L.push(`| ${i + 1} | \`${f.id}\` | ${cell(f.hu)} | ${f.wp} | ${DK[e.desk] || '?'} | ${cell(what)} |`);
  });
  L.push('', '### 3. A hiányok munkacsomagjai', '');
  L.push('| WP | Oldal | Mit | Tagjai |', '|---|---|---|---|');
  for (const [wp, q] of Object.entries(parity.queue)) {
    const members = q.side === 'phone'
      ? Object.entries(parity.desk).filter(([, e]) => e.wp === wp).map(([id]) => '`' + id + '`')
      : Object.entries(parity.phone).filter(([, e]) => e.wp === wp).map(([id]) => '`' + id + '`');
    L.push(`| ${wp} | ${q.side === 'phone' ? 'telefon' : 'Asztal'} | ${cell(q.hu)} | ${members.join(', ')} |`);
  }
  L.push('', END);
  return L.join('\n');
}

function docText(data) {
  const now = fs.existsSync(DOC) ? fs.readFileSync(DOC, 'utf8').replace(/\r\n/g, '\n') : '';
  const a = now.indexOf(BEGIN), b = now.indexOf(END);
  if (a < 0 || b < a) throw new Error('parity: docs/mobile/PARITY.md has no ' + BEGIN.slice(0, 20) + ' ... ' + END + ' block');
  return now.slice(0, a) + table(data) + now.slice(b + END.length);
}

function main() {
  let data;
  try { data = load(); } catch (e) { console.log('Hiba: ' + ascii(e.message)); process.exit(1); }
  const err = check(data);
  if (err.length) {
    console.log('Paritas: ' + err.length + ' hiba');
    for (const e of err) console.log('  - ' + ascii(e));
    process.exit(1);
  }
  const files = [[CARDS, cards(data)], [DOC, docText(data)]];
  const count = (o, k, f) => Object.values(o).filter(e => e[f] === k).length;
  const sum = `${data.units.length} Asztal egyseg (szurke ${count(data.parity.desk, 'grey', 'phone')}, hiany ${count(data.parity.desk, 'gap', 'phone')}), ` +
    `${data.feats.length} telefon funkcio (szurke ${count(data.parity.phone, 'grey', 'desk')}, hiany ${count(data.parity.phone, 'gap', 'desk')})`;
  if (process.argv.includes('--check')) {
    let bad = 0;
    for (const [f, s] of files) {
      const now = fs.existsSync(f) ? fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n') : '';
      if (now !== s) { console.log('elavult: ' + path.relative(REPO, f) + '  (futtasd: node tools/parity.js)'); bad++; }
    }
    if (!bad) console.log('Rendben: ' + sum);
    process.exit(bad ? 1 : 0);
  }
  for (const [f, s] of files) fs.writeFileSync(f, s);
  console.log('Megirva: phone-cards.json + PARITY.md; ' + sum);
}

if (require.main === module) main();
module.exports = { load, check, phoneFeatures, FRAME };
