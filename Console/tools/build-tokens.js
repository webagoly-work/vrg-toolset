/* design/tokens.json + design/sunlight.json -> www/css/tokens.css. node tools/build-tokens.js
   The sunlight theme overrides the data colours. .chrome keeps the HUD colours in both themes,
   because the charcoal plates do not change. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, f), 'utf8'));

export function buildTokens(tokens, sunlight) {
  const hud = tokens.color.tokens;
  const vars = (list) => list.map(([k, v]) => `  --${k}: ${v};`).join('\n');
  const colours = hud.map((t) => [t.name, t.value]);
  const other = [...tokens.spacing.tokens, ...tokens.radius.tokens].map((t) => [t.name, t.value]);
  const fam = Object.entries(tokens.type.families).map(([k, v]) => ['f-' + k, v]);
  const overridden = colours.filter(([k]) => k in sunlight.tokens);
  return `/* Generated by tools/build-tokens.js from design/tokens.json and design/sunlight.json. Do not edit. */
:root {
${vars(colours)}
${vars(other)}
${vars(fam)}
}
[data-theme="sun"] {
${vars(Object.entries(sunlight.tokens))}
}
[data-theme="sun"] .chrome {
${vars(overridden)}
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const css = buildTokens(read('design/tokens.json'), read('design/sunlight.json'));
  fs.writeFileSync(path.join(ROOT, 'www/css/tokens.css'), css);
  console.log('www/css/tokens.css written');
}
