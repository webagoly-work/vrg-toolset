#!/usr/bin/env node
/* Writes www/precache.js: every file the app needs offline, and a version from their content, so any change
   to www/ makes a new cache by itself. serve.js builds the same thing on request for development. */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const WWW = path.join(path.dirname(fileURLToPath(import.meta.url)), '../www');
const SKIP = new Set(['precache.js', 'sw.js']);

const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
  const full = path.join(dir, e.name);
  return e.isDirectory() ? walk(full) : [full];
});

export function precacheSource() {
  const files = walk(WWW).map((f) => path.relative(WWW, f).replaceAll(path.sep, '/')).filter((f) => !SKIP.has(f)).sort();
  const hash = crypto.createHash('sha256');
  for (const f of files) hash.update(f).update(fs.readFileSync(path.join(WWW, f)));
  hash.update(fs.readFileSync(path.join(WWW, 'sw.js')));
  const list = files.map((f) => `  './${f}',`).join('\n');
  return `/* generated by tools/build-precache.js */\nself.PRECACHE = { version: '${hash.digest('hex').slice(0, 12)}', files: [\n${list}\n] };\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(WWW, 'precache.js'), precacheSource());
  console.log('www/precache.js written');
}
